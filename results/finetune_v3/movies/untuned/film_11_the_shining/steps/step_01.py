# --- SNOW GROUND ---
ground = bpy.data.meshes.new("Ground")
verts = []
edges = []
faces = []
n = 50
size = 120
for i in range(n):
    for j in range(n):
        x = -size/2 + i * (size/n)
        z = -size/2 + j * (size/n)
        y = random.uniform(-0.05, 0.15)
        verts.append((x, y, z))
for i in range(n-1):
    for j in range(n-1):
        v0 = i*n + j
        v1 = v0 + 1
        v2 = v0 + n
        v3 = v2 + 1
        faces.append((v0, v1, v3, v2))
ground.from_pydata(verts, [], faces)
ground_obj = bpy.data.objects.new("Ground", ground)
bpy.context.collection.objects.link(ground_obj)
ground_obj.data.materials.append(mat_snow)

